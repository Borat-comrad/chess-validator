import geometry

tests = (
    # --- KNIGHT ---

    # Обычный допустимый ход
    ("N", "b", 1, "c", 3, True),

    # Допустимый ход в другом направлении
    ("N", "f", 3, "e", 5, True),

    # Вторая ориентация буквы Г: 2 по вертикали, 1 по горизонтали
    ("N", "b", 1, "d", 2, True),

    # Похожий, но неправильный ход: 1 и 3
    ("N", "e", 5, "f", 8, False),

    # Конь не ходит по диагонали
    ("N", "b", 1, "c", 2, False),

    # Та же клетка
    ("N", "b", 1, "b", 1, False),


    # --- BISHOP ---

    # Допустимая длинная диагональ
    ("B", "a", 1, "h", 8, True),

    # Диагональ в обратную сторону
    ("B", "h", 8, "a", 1, True),

    # Не диагональ
    ("B", "c", 1, "c", 5, False),

    # Почти диагональ, но проекции различаются
    ("B", "c", 1, "f", 5, False),


    # --- ROOK ---

    # Вертикальный ход
    ("R", "a", 1, "a", 8, True),

    # Горизонтальный ход
    ("R", "a", 4, "h", 4, True),

    # Диагональ запрещена
    ("R", "a", 1, "h", 8, False),

    # Та же клетка
    ("R", "d", 4, "d", 4, False),


    # --- QUEEN ---

    # Ферзь как слон
    ("Q", "a", 1, "h", 8, True),

    # Ферзь как ладья
    ("Q", "d", 1, "d", 8, True),

    # Движение, которое не подходит ни слону, ни ладье
    ("Q", "d", 4, "f", 7, False),


    # --- KING ---

    # Один шаг по горизонтали
    ("K", "e", 4, "f", 4, True),

    # Один шаг по вертикали
    ("K", "e", 4, "e", 5, True),

    # Один шаг по диагонали
    ("K", "e", 4, "f", 5, True),

    # Два поля — слишком далеко
    ("K", "e", 4, "e", 6, False),

    # Та же клетка
    ("K", "e", 4, "e", 4, False),


    # --- PAWN ---
    # Здесь проверяем только значения по умолчанию:
    # color="w", is_take=False

    # Белая пешка на один шаг
    ("P", "e", 2, "e", 3, True),

    # Белая пешка на два шага со стартовой позиции
    ("P", "e", 2, "e", 4, True),

    # Два шага не со стартовой позиции
    ("P", "e", 3, "e", 5, False),

    # Назад ходить нельзя
    ("P", "e", 4, "e", 3, False),

    # Обычным ходом нельзя менять вертикаль
    ("P", "e", 2, "f", 3, False),


    # --- ОБЩИЕ ЗАПРЕТЫ / VALIDATE_MOVE ---

    # Несуществующая фигура
    ("X", "a", 1, "a", 2, False),

    # Несуществующая вертикаль
    ("N", "z", 1, "c", 2, False),

    # Горизонталь ниже доски
    ("R", "a", 0, "a", 5, False),

    # Горизонталь выше доски
    ("B", "a", 1, "i", 9, False),
)

for num, test in enumerate(tests):
    figure = test[0]
    ver_1 = test[1]
    hor_1 = test[2]
    ver_2 = test[3]
    hor_2 = test[4]
    result = test[5]

    res_of_try = geometry.validate_move(figure, ver_1, hor_1, ver_2, hor_2)

    if res_of_try == result:
        print(f"Тест {num+1} прошел успешно")
    else:
        print(f"Тест {num+1} провален")